export function calculateLevel(points: number) {
  for (let i = LEVEL_TIERS.length - 1; i >= 0; i--) {
    if (points >= LEVEL_TIERS[i].minPoints) {
      return LEVEL_TIERS[i];
    }
  }
  return LEVEL_TIERS[0];
}

